    question_text: Optional[str] = Field(default=None, description="Question statement evaluated")
    filename: Optional[str] = Field(default=None, description="Source PDF filename or sample title")
    scorecard: ConsolidatedScorecard
    executive_summary: Optional[str] = Field(default=None, description="Deprecated; formerly candid examiner assessment")
    demand_evaluation: DemandEvaluation
    intro_evaluation: IntroEvaluation
    structure_evaluation: StructureEvaluation
    conclusion_evaluation: ConclusionEvaluation
    knowledge_evaluation: KnowledgeEvaluation
    transformation_roadmap: TransformationRoadmap
    top_value_additions: List[str] = Field(default_factory=list)
    total_latency_seconds: float = 0.0
    token_usage_breakdown: Dict[str, TokenUsage] = Field(default_factory=dict, description="Input/Output token telemetry per agent")
    total_token_usage: TokenUsage = Field(default_factory=TokenUsage, description="Total aggregated input/output tokens")
    is_empty_submission: bool = False
    trace_id: Optional[str] = Field(default=None, description="Langfuse observability trace ID")
    trace_url: Optional[str] = Field(default=None, description="Direct URL to trace in Langfuse dashboard")
